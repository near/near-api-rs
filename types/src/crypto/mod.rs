use std::{
    fmt::{Display, Formatter},
    str::FromStr,
};

use crate::errors::{DataConversionError, KeyTypeError};

pub mod public_key;
pub mod secret_key;
pub mod signature;

pub const ED25519_PUBLIC_KEY_LENGTH: usize = 32;
pub const SECP256K1_PUBLIC_KEY_LENGTH: usize = 64;
pub const COMPONENT_SIZE: usize = 32;
pub const SECP256K1_SIGNATURE_LENGTH: usize = 65;
/// ML-DSA-65 (FIPS 204) public key length in bytes.
pub const ML_DSA_65_PUBLIC_KEY_LENGTH: usize = 1952;
/// ML-DSA-65 (FIPS 204) expanded secret key (`skEncode`) length in bytes.
pub const ML_DSA_65_SECRET_KEY_LENGTH: usize = 4032;
/// ML-DSA-65 (FIPS 204) signature length in bytes.
pub const ML_DSA_65_SIGNATURE_LENGTH: usize = 3309;
/// ML-DSA-65 (FIPS 204) seed length in bytes.
pub const ML_DSA_65_SEED_LENGTH: usize = 32;

#[derive(Debug, Copy, Clone, serde::Serialize, serde::Deserialize)]
#[cfg_attr(test, derive(bolero::TypeGenerator))]
pub enum KeyType {
    ED25519 = 0,
    SECP256K1 = 1,
    MLDSA65 = 2,
}

impl Display for KeyType {
    fn fmt(&self, f: &mut Formatter<'_>) -> Result<(), std::fmt::Error> {
        f.write_str(match self {
            Self::ED25519 => "ed25519",
            Self::SECP256K1 => "secp256k1",
            Self::MLDSA65 => "ml-dsa-65",
        })
    }
}

impl FromStr for KeyType {
    type Err = KeyTypeError;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        let lowercase_key_type = value.to_ascii_lowercase();
        match lowercase_key_type.as_str() {
            "ed25519" => Ok(Self::ED25519),
            "secp256k1" => Ok(Self::SECP256K1),
            "ml-dsa-65" => Ok(Self::MLDSA65),
            _ => Err(KeyTypeError::InvalidKeyFormat(
                lowercase_key_type.to_string(),
            )),
        }
    }
}

impl TryFrom<u8> for KeyType {
    type Error = KeyTypeError;

    fn try_from(value: u8) -> Result<Self, Self::Error> {
        match value {
            0 => Ok(Self::ED25519),
            1 => Ok(Self::SECP256K1),
            2 => Ok(Self::MLDSA65),
            unknown_key_type => Err(KeyTypeError::InvalidKeyTypeByteIndex(unknown_key_type)),
        }
    }
}

fn split_key_type_data(value: &str) -> Result<(KeyType, &str), DataConversionError> {
    if let Some((prefix, key_data)) = value.split_once(':') {
        Ok((KeyType::from_str(prefix)?, key_data))
    } else {
        // If there is no prefix then we Default to ED25519.
        Ok((KeyType::ED25519, value))
    }
}

#[cfg(test)]
mod tests {
    use crate::CryptoHash;

    use std::str::FromStr;

    use super::{
        KeyType, ML_DSA_65_PUBLIC_KEY_LENGTH, ML_DSA_65_SIGNATURE_LENGTH,
        public_key::PublicKey,
        secret_key::{MlDsa65SecretKey, SecretKey},
        signature::Signature,
    };

    #[test]
    fn signature_verify_fuzzer() {
        bolero::check!().with_type().for_each(
            |(key_type, sign, data, public_key): &(KeyType, [u8; 65], [u8; 32], PublicKey)| {
                let signature = match key_type {
                    KeyType::ED25519 => {
                        Signature::from_parts(KeyType::ED25519, &sign[..64]).unwrap()
                    }
                    KeyType::SECP256K1 => {
                        Signature::from_parts(KeyType::SECP256K1, &sign[..65]).unwrap()
                    }
                    KeyType::MLDSA65 => {
                        // The generated bytes are too short for an ML-DSA-65 signature, so repeat them.
                        let sign: Vec<u8> = sign
                            .iter()
                            .copied()
                            .cycle()
                            .take(ML_DSA_65_SIGNATURE_LENGTH)
                            .collect();
                        Signature::from_parts(KeyType::MLDSA65, &sign).unwrap()
                    }
                };
                let _ = signature.verify(CryptoHash(*data), public_key.clone());
            },
        );
    }

    #[test]
    fn regression_signature_verification_originally_failed() {
        let signature = Signature::from_parts(KeyType::SECP256K1, &[4; 65]).unwrap();
        let _ = signature.verify(CryptoHash([0; 32]), PublicKey::empty(KeyType::SECP256K1));
    }

    #[test]
    fn test_ml_dsa_65_key_type() {
        assert_eq!(KeyType::MLDSA65.to_string(), "ml-dsa-65");
        assert!(matches!("ml-dsa-65".parse(), Ok(KeyType::MLDSA65)));
        assert!(matches!("ML-DSA-65".parse(), Ok(KeyType::MLDSA65)));
        assert!(matches!(KeyType::try_from(2u8), Ok(KeyType::MLDSA65)));
        assert!(KeyType::try_from(3u8).is_err());
        // The on-trie hash form nodes return for access keys is not a key type.
        assert!("ml-dsa-65-hash".parse::<KeyType>().is_err());
        // Borsh tags must never change: they are part of the protocol.
        assert_eq!(KeyType::MLDSA65 as u8, 2);
    }

    #[test]
    fn test_ml_dsa_65_public_key() {
        let public_key = SecretKey::MLDSA65(MlDsa65SecretKey::from_seed(&[1; 32])).public_key();
        assert!(matches!(public_key.key_type(), KeyType::MLDSA65));
        assert_eq!(public_key.key_data().len(), ML_DSA_65_PUBLIC_KEY_LENGTH);
        assert_eq!(public_key.len(), 1 + ML_DSA_65_PUBLIC_KEY_LENGTH);

        // String and serde round trips.
        let serialized = public_key.to_string();
        assert!(serialized.starts_with("ml-dsa-65:"));
        assert_eq!(PublicKey::from_str(&serialized).unwrap(), public_key);
        let json = serde_json::to_string(&public_key).unwrap();
        assert_eq!(
            serde_json::from_str::<PublicKey>(&json).unwrap(),
            public_key
        );
        assert_eq!(format!("{public_key:?}"), serialized);

        // Borsh: tag 2 followed by the raw key.
        let borsh = borsh::to_vec(&public_key).unwrap();
        assert_eq!(borsh.len(), public_key.len());
        assert_eq!(borsh[0], 2);
        assert_eq!(&borsh[1..], public_key.key_data());
        assert_eq!(borsh::from_slice::<PublicKey>(&borsh).unwrap(), public_key);

        // Truncated and over-long input is rejected rather than silently accepted.
        assert!(borsh::from_slice::<PublicKey>(&borsh[..borsh.len() - 1]).is_err());
        let truncated = format!(
            "ml-dsa-65:{}",
            bs58::encode(&public_key.key_data()[1..]).into_string()
        );
        assert!(PublicKey::from_str(&truncated).is_err());
        let too_long = format!(
            "ml-dsa-65:{}",
            bs58::encode([public_key.key_data(), &[0]].concat()).into_string()
        );
        assert!(PublicKey::from_str(&too_long).is_err());
        assert!(PublicKey::from_str(&serialized.replace("ml-dsa-65:", "ml-dsa-65-hash:")).is_err());
        assert!(PublicKey::from_str("ml-dsa-65:").is_err());

        // `empty`, `Hash` and ordering behave like the other key types.
        let empty = PublicKey::empty(KeyType::MLDSA65);
        assert_eq!(empty.key_data(), &[0u8; ML_DSA_65_PUBLIC_KEY_LENGTH][..]);
        assert_ne!(empty, public_key);
        let mut keys = std::collections::HashSet::new();
        assert!(keys.insert(public_key.clone()));
        assert!(!keys.insert(public_key));
        assert!(keys.insert(empty));
        // Different key types never collide, even with identical raw bytes.
        assert_ne!(
            PublicKey::empty(KeyType::ED25519),
            PublicKey::empty(KeyType::MLDSA65)
        );
        assert!(PublicKey::empty(KeyType::SECP256K1) < PublicKey::empty(KeyType::MLDSA65));
    }

    #[test]
    fn test_ml_dsa_65_signature() {
        let secret_key = SecretKey::MLDSA65(MlDsa65SecretKey::from_seed(&[2; 32]));
        let signature = secret_key.sign(CryptoHash::hash(b"hello"));
        let Signature::MLDSA65(inner) = &signature else {
            unreachable!("an ML-DSA-65 key produces an ML-DSA-65 signature");
        };
        assert_eq!(inner.0.len(), ML_DSA_65_SIGNATURE_LENGTH);

        // from_parts accepts exactly the right length.
        let raw = &inner.0[..];
        assert_eq!(
            Signature::from_parts(KeyType::MLDSA65, raw).unwrap(),
            signature
        );
        assert!(Signature::from_parts(KeyType::MLDSA65, &raw[1..]).is_err());
        assert!(Signature::from_parts(KeyType::MLDSA65, &[raw, &[0]].concat()).is_err());
        assert!(Signature::from_parts(KeyType::MLDSA65, &[]).is_err());

        // String and serde round trips.
        let serialized = signature.to_string();
        assert!(serialized.starts_with("ml-dsa-65:"));
        assert_eq!(Signature::from_str(&serialized).unwrap(), signature);
        let json = serde_json::to_string(&signature).unwrap();
        assert_eq!(serde_json::from_str::<Signature>(&json).unwrap(), signature);
        assert!(Signature::from_str(&format!("ml-dsa-65:{}", &serialized[11..100])).is_err());

        // Borsh: tag 2 followed by the raw signature.
        let borsh = borsh::to_vec(&signature).unwrap();
        assert_eq!(borsh.len(), 1 + ML_DSA_65_SIGNATURE_LENGTH);
        assert_eq!(borsh[0], 2);
        assert_eq!(&borsh[1..], raw);
        assert_eq!(borsh::from_slice::<Signature>(&borsh).unwrap(), signature);
        assert!(borsh::from_slice::<Signature>(&borsh[..borsh.len() - 1]).is_err());

        // An all-zero (malformed) signature fails verification instead of panicking.
        let zero =
            Signature::from_parts(KeyType::MLDSA65, &[0; ML_DSA_65_SIGNATURE_LENGTH]).unwrap();
        assert!(!zero.verify(CryptoHash::hash(b"hello"), secret_key.public_key()));
        // So does a valid signature checked against an all-zero public key.
        assert!(!signature.verify(
            CryptoHash::hash(b"hello"),
            PublicKey::empty(KeyType::MLDSA65)
        ));
    }

    #[test]
    fn test_invalid_data() {
        // cspell:disable-next-line
        let invalid = "\"secp256k1:2xVqteU8PWhadHTv99TGh3bSf\"";
        assert!(serde_json::from_str::<PublicKey>(invalid).is_err());
        assert!(serde_json::from_str::<SecretKey>(invalid).is_err());
        assert!(serde_json::from_str::<Signature>(invalid).is_err());
    }
}
